#!/usr/bin/env python3
"""Generate the Mazak auto tool measure side panel (2026-10-11).

Writes three files next to this script:
    toolmeasure.xml              PyVCP panel: "Tool measure" tab (4 tabs x 20 tick boxes,
                                 All/Clear per tab) + "Toolchanger" tab, which is
                                 copied in from toolchanger_panel.xml
    toolmeasure_postgui.hal      Measure button + All/Clear logic (sourced from custom_postgui.hal)
    sub_progs/.toolsensor.ngc    reads the 80 tick boxes, calls .toolsensor_one for each

sub_progs/.toolsensor_one.ngc (the actual measuring, one tool) is hand written,
not generated. Edit TOOLS / PER_TAB / COLS below and re-run to change the layout:
    python3 build_toolmeasure.py
SCALE below shrinks or grows the whole panel.
"""
import os
import re

TOOLS = 80
PER_TAB = 20
COLS = 2
# Whole panel size: 1.0 = as written, 0.8 = 20 % smaller (fonts, LEDs,
# button padding, borders).  Change it and re-run.
SCALE = 0.8
HERE = os.path.dirname(os.path.abspath(__file__))
TABS = TOOLS // PER_TAB


def tab_range(t):
    first = t * PER_TAB + 1
    return first, first + PER_TAB - 1


def checkbutton(n):
    return f'''            <checkbutton>
              <halpin>"ts-t{n}"</halpin>
              <text>"T{n}"</text>
              <width>5</width>
              <anchor>"w"</anchor>
              <font>("Helvetica",10)</font>
              <fg>"#1f2933"</fg>
              <selectcolor>"#ffffff"</selectcolor>
              <activebackground>"#dbe4f0"</activebackground>
              <initval>0</initval>
            </checkbutton>
'''


# Colours copied from the linear rail panel (cnc_mill_linear_rail/custompanel1.xml)
GREEN, GREEN_ACTIVE = "#2e9e44", "#26863a"


def button(pin, text):
    return f'''          <button>
            <halpin>"{pin}"</halpin>
            <text>"{text}"</text>
            <font>("Helvetica",10,"bold")</font>
            <bg>"{GREEN}"</bg>
            <fg>"#ffffff"</fg>
            <activebackground>"{GREEN_ACTIVE}"</activebackground>
            <activeforeground>"#ffffff"</activeforeground>
            <relief>"raised"</relief>
            <bd>3</bd>
            <padx>8</padx>
          </button>
'''


def build_xml():
    names = ", ".join(f'"T{a}-{b}"' for a, b in map(tab_range, range(TABS)))
    out = ["<?xml version='1.0' encoding='UTF-8'?>\n",
           "<!-- GENERATED by build_toolmeasure.py - edit that and re-run, not this file -->\n",
           "<pyvcp>\n\n",
           '<tabs>\n  <names>["Tool measure", "Toolchanger", "ATC manual"]</names>\n\n',
           '<labelframe text="Auto Touch Off Tools">\n',
           '  <font>("Helvetica",12,"bold")</font>\n  <fg>"#000000"</fg>\n',
           '  <relief>"groove"</relief>\n  <bd>2</bd>\n  <vbox>\n\n',
           '  <label>\n    <text>"Tick tools to measure - dia from tool table"</text>\n'
           '    <font>("Helvetica",9)</font>\n    <fg>"#000000"</fg>\n  </label>\n\n',
           f"  <tabs>\n    <names>[{names}]</names>\n"]
    rows = PER_TAB // COLS
    for t in range(TABS):
        first, _ = tab_range(t)
        out.append(f"\n    <!-- tab {t + 1}: T{first}-T{first + PER_TAB - 1} -->\n")
        out.append("    <vbox>\n        <hbox>\n")
        for c in range(COLS):
            out.append("          <vbox>\n")
            for r in range(rows):
                out.append(checkbutton(first + c * rows + r))
            out.append("          </vbox>\n")
        out.append("        </hbox>\n        <hbox>\n")
        out.append(button(f"ts-all-{t + 1}", "All"))
        out.append(button(f"ts-clear-{t + 1}", "Clear"))
        out.append("        </hbox>\n    </vbox>\n")
    out.append("  </tabs>\n\n")
    out.append('  <label>\n    <text>" "</text>\n  </label>\n')
    out.append(f'''  <button>
    <halpin>"measure-tools"</halpin>
    <text>"Measure Tools"</text>
    <font>("Helvetica",12,"bold")</font>
    <bg>"{GREEN}"</bg>
    <fg>"#ffffff"</fg>
    <activebackground>"{GREEN_ACTIVE}"</activebackground>
    <activeforeground>"#ffffff"</activeforeground>
    <relief>"raised"</relief>
    <bd>4</bd>
    <padx>10</padx>
    <pady>6</pady>
  </button>

  </vbox>
</labelframe>

''')
    # second + third tabs: toolchanger, and ATC manual (hand written, two
    # top-level <vbox>es in that file)
    with open(os.path.join(HERE, "toolchanger_panel.xml")) as f:
        out.append(f.read())
    out.append("\n</tabs>\n\n</pyvcp>\n")
    return scale("".join(out))


def scale(xml):
    """Shrink/grow the whole panel by SCALE: fonts, LEDs, padding, borders."""
    def n(m):
        return m.group(1) + str(max(1, round(int(m.group(2)) * SCALE))) + m.group(3)
    xml = re.sub(r'(\("Helvetica",)(\d+)(\b)', n, xml)
    return re.sub(r'(<(?:size|padx|pady|bd)>)(\d+)(</)', n, xml)


def build_hal():
    names = ",".join(f"tsel{n}" for n in range(1, TOOLS + 1))
    out = ['''# GENERATED by build_toolmeasure.py - edit that and re-run, not this file.
# Auto tool measure side panel (toolmeasure.xml). Sourced from custom_postgui.hal,
# because the pyvcp.* pins only exist once the GUI is up.

# Measure Tools button -> o<.toolsensor> call ([HALUI]MDI_COMMAND index 00)
net ts-measure-tools pyvcp.measure-tools => halui.mdi-command-00

# All / Clear buttons.
# A pyvcp checkbutton can't be set from HAL, it only has a .changepin input that
# TOGGLES it. So one lut5 per tool decides whether to toggle:
#     in-0 = the box (pyvcp.ts-tN)   in-1 = All button   in-2 = Clear button
#     toggle when  (All and box off)  or  (Clear and box on)
# Once the box has flipped the condition goes false, so holding a button can't
# make it flicker. Both buttons at once: All wins.
#     function = 0x64  (truth table bits 2, 5, 6)
#
# pyvcp only looks at .changepin every 100 ms, so a quick click on All/Clear
# could come and go between two looks and do nothing. A oneshot stretches every
# press to 0.3 s, which pyvcp is sure to see.
''', f"loadrt lut5 names={names}\n",
           "loadrt oneshot names=" + ",".join(f"tsall{t},tsclr{t}" for t in range(1, TABS + 1)) + "\n"]
    for n in range(1, TOOLS + 1):
        out.append(f"addf tsel{n} servo-thread\n")
    for t in range(1, TABS + 1):
        out.append(f"addf tsall{t} servo-thread\naddf tsclr{t} servo-thread\n")
    for t in range(TABS):
        first, last = tab_range(t)
        out.append(f"\n# tab {t + 1}: T{first}-T{last}\n")
        all_pins = " ".join(f"tsel{n}.in-1" for n in range(first, last + 1))
        clr_pins = " ".join(f"tsel{n}.in-2" for n in range(first, last + 1))
        for os_, btn in ((f"tsall{t + 1}", f"ts-all-{t + 1}"), (f"tsclr{t + 1}", f"ts-clear-{t + 1}")):
            out.append(f"setp {os_}.width 0.3\nsetp {os_}.rising 1\nsetp {os_}.falling 0\n")
            out.append(f"net {btn}-btn pyvcp.{btn} => {os_}.in\n")
        out.append(f"net ts-all-{t + 1}   tsall{t + 1}.out => {all_pins}\n")
        out.append(f"net ts-clear-{t + 1} tsclr{t + 1}.out => {clr_pins}\n")
        for n in range(first, last + 1):
            out.append(f"setp tsel{n}.function 0x64\n")
            out.append(f"net ts-t{n}     pyvcp.ts-t{n}     => tsel{n}.in-0\n")
            out.append(f"net ts-t{n}-chg tsel{n}.out   => pyvcp.ts-t{n}.changepin\n")
    return "".join(out)


def build_ngc():
    out = [f'''(  .toolsensor.ngc  -  GENERATED by build_toolmeasure.py, do not edit    )
(                                                                         )
(  Fired by the Measure Tools button on the side panel.                   )
(  Reads the {TOOLS} tick boxes, then measures each ticked tool with           )
(  o<.toolsensor_one> - all the real work and the settings are in there.  )

o<.toolsensor> sub

  ; Force a state sync before reading any HAL pin. Without this, #<_hal[...]>
  ; returns the value the pin had when the program STARTED, not what is ticked
  ; on the panel now. M66 E0 L0 is the documented dummy-read workaround.
  m66 e0 l0

  ; Read every box up front, before the first tool change.
  #<count> = 0
''']
    for n in range(1, TOOLS + 1):
        # separate lines: all assignments on one line are evaluated before any is set
        out.append(f"  #<t{n}> = #<_hal[pyvcp.ts-t{n}]>\n"
                   f"  #<count> = [#<count> + #<t{n}>]\n")
    out.append('''
  o<none> if [#<count> EQ 0]
    (msg, tool sensor: no tools ticked)
    o<.toolsensor> return
  o<none> endif

''')
    for n in range(1, TOOLS + 1):
        out.append(f"  o<m{n}> if [#<t{n}> EQ 1]\n"
                   f"    o<.toolsensor_one> call [{n}]\n"
                   f"  o<m{n}> endif\n")
    out.append('''
  (msg, tool sensor: measuring done)

o<.toolsensor> endsub
''')
    return "".join(out)


if __name__ == "__main__":
    for path, text in (("toolmeasure.xml", build_xml()),
                       ("toolmeasure_postgui.hal", build_hal()),
                       ("sub_progs/.toolsensor.ngc", build_ngc())):
        with open(os.path.join(HERE, path), "w") as f:
            f.write(text)
        print("wrote", path)
